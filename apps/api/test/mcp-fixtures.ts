import { readFile, writeFile, mkdir } from "node:fs/promises";
import { z } from "zod";
import { ToolSchema } from "@modelcontextprotocol/sdk/types.js";
import { format, resolveConfig } from "prettier";
import {
  getOutputSchema,
  searchOutputSchema,
  sqlOutputSchema,
  jsonValueSchema,
  type JsonValue,
} from "@agentcommons/core";
import { formatGet, formatSearch, formatSql } from "@agentcommons/core/format";

const mcpFixtureSchema = z.strictObject({
  tools: z.array(ToolSchema),
  /** The `administration` group as an administrator key lists it (ADR 0072). */
  administration: z.array(ToolSchema),
  search: searchOutputSchema,
  get: getOutputSchema,
  sql: sqlOutputSchema,
});
const fixtureUrl = new URL(
  "../../../fixtures/contracts/mcp.json",
  import.meta.url,
);
const specUrl = new URL("../../../docs/SPEC.md", import.meta.url);
export const appendixMarker =
  "## Appendix C. What the agent sees (regenerated by contract tests)";

/** Replace only nondeterministic identifiers, receipt times, and SQL timing. */
function normalizeMcpFixture(value: unknown): z.infer<typeof mcpFixtureSchema> {
  const identifiers = new Map<string, string>();
  const normalize = (value: JsonValue, field = ""): JsonValue => {
    if (Array.isArray(value)) return value.map((item) => normalize(item));
    if (value !== null && typeof value === "object")
      return Object.fromEntries(
        Object.entries(value).map(([key, item]) => [key, normalize(item, key)]),
      );
    if (field === "duration_ms") return 0;
    if (typeof value !== "string") return value;
    if (/^\d{4}-\d\d-\d\dT/.test(value)) return "2026-09-07T01:00:00.000Z";
    if (
      /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
        value,
      )
    ) {
      if (!identifiers.has(value))
        identifiers.set(
          value,
          `00000000-0000-4000-8000-${String(identifiers.size + 1).padStart(12, "0")}`,
        );
      return identifiers.get(value) ?? value;
    }
    if (field === "organization_id") return "fixture-organization";
    return value;
  };
  return mcpFixtureSchema.parse(normalize(jsonValueSchema.parse(value)));
}
export async function renderAppendix(
  fixture: z.infer<typeof mcpFixtureSchema>,
): Promise<string> {
  const fields = (inputSchema: z.infer<typeof ToolSchema>["inputSchema"]) => {
    const objects = z
      .array(z.looseObject({ properties: z.record(z.string(), z.unknown()) }))
      .parse(
        Array.isArray(inputSchema.anyOf) ? inputSchema.anyOf : [inputSchema],
      );
    return [
      ...new Set(objects.flatMap((object) => Object.keys(object.properties))),
    ]
      .map((field) => `\`${field}\``)
      .join(", ");
  };
  const markdown = `${appendixMarker}\n\nGenerated from the real PostgreSQL and ClickHouse and official MCP SDK contract fixture at\n\`fixtures/contracts/mcp.json\`. Regenerate with\n\`UPDATE_MCP_FIXTURES=1 pnpm exec vitest run apps/api/test/transport.integration.test.ts\`.\nIdentifiers, receipt timestamps, and SQL timings are normalized for reproducibility.\n\nEvery \`sessions:read\` key lists \`search\`, \`get\` and \`sql\`, and nothing else by default. A key\nthat grants the \`dashboards\` tool group also lists \`dashboard_list\`, \`dashboard_get\`,\n\`dashboard_render\`, \`dashboard_save\` and \`dashboard_delete\`; effective admin keys add\n\`set_visibility\`, \`purge\`, \`audit\` and \`status\`, and \`dashboard_set_default\` when they hold\nboth (§8.2). An admin key that also grants the \`administration\` group lists one\n\`admin_<resource>_<verb>\` tool per \`/admin\` route after those, derived from the route table\n(ADR 0072); they are summarized after the JSON below.\n\n\`tools/list\` as an effective admin key with the \`dashboards\` group receives it, complete. Output\nschemas are not shipped (§8.2); results are validated server-side and returned as\n\`structuredContent\`. The default catalog is the first three tools; every catalog stays within\nthe byte budgets of §8.2.\n\n\`\`\`json\n${JSON.stringify(
    fixture.tools.map(({ name, description, inputSchema, annotations }) => ({
      name,
      description,
      inputSchema,
      annotations,
    })),
    null,
    2,
  )}\n\`\`\`\n\nThe \`administration\` group, as the same key with that grant lists it. Each input is the\nroute's params, query and body merged into one object (the REST \`format\` switch excluded);\nthe complete schemas are the route's in the OpenAPI document.\n\n| Tool | Does | Fields |\n| --- | --- | --- |\n${fixture.administration
    .map(
      (tool) =>
        `| \`${tool.name}\` | ${(tool.description ?? "").split(". ").slice(1).join(". ")} | ${fields(tool.inputSchema)} |`,
    )
    .join("\n")}\n\n${(
    [
      ["search", formatSearch(fixture.search)],
      ["get", formatGet(fixture.get)],
      ["sql", formatSql(fixture.sql)],
    ] as const
  )
    .map(
      ([name, formatted]) =>
        `\`${name}\` text rendering; structuredContent contains the corresponding schema-validated fixture value.\n\n\`\`\`text\n${formatted.text}\n\`\`\``,
    )
    .join(
      "\n\n",
    )}\n\nTool failures return \`isError: true\` and a text JSON error without structuredContent.\n`;
  return format(markdown, {
    ...(await resolveConfig(specUrl)),
    parser: "markdown",
  });
}
/** Rewrite the generated Appendix C block of the specification from a fixture. */
async function writeAppendix(
  fixture: z.infer<typeof mcpFixtureSchema>,
): Promise<void> {
  const spec = await readFile(specUrl, "utf8");
  await writeFile(
    specUrl,
    `${spec.slice(0, spec.indexOf(appendixMarker))}${await renderAppendix(fixture)}`,
  );
}
export async function checkMcpFixture(value: unknown): Promise<void> {
  const fixture = normalizeMcpFixture(value);
  if (process.env.UPDATE_MCP_FIXTURES === "1") {
    await mkdir(new URL(".", fixtureUrl), { recursive: true });
    await writeFile(fixtureUrl, `${JSON.stringify(fixture, null, 2)}\n`);
    await writeAppendix(fixture);
  } else {
    const expected = mcpFixtureSchema.parse(
      JSON.parse(await readFile(fixtureUrl, "utf8")),
    );
    if (JSON.stringify(fixture) !== JSON.stringify(expected))
      throw new Error(
        "The MCP contract fixture changed. Review and regenerate Appendix C.",
      );
  }
}
export async function readMcpFixture() {
  return mcpFixtureSchema.parse(JSON.parse(await readFile(fixtureUrl, "utf8")));
}
