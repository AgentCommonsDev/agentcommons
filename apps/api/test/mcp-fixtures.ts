import { readFile, writeFile, mkdir } from "node:fs/promises";
import { z } from "zod";
import { ToolSchema } from "@modelcontextprotocol/sdk/types.js";
import { format, resolveConfig } from "prettier";
import {
  getOutputSchema,
  searchOutputSchema,
  sqlOutputSchema,
  jsonValueSchema,
  type JsonValue,
} from "@agentcommons/core";
import { formatGet, formatSearch, formatSql } from "@agentcommons/core/format";

export const mcpFixtureSchema = z.strictObject({
  tools: z.array(ToolSchema),
  search: searchOutputSchema,
  get: getOutputSchema,
  sql: sqlOutputSchema,
});
const fixtureUrl = new URL(
  "../../../fixtures/contracts/mcp.json",
  import.meta.url,
);
const specUrl = new URL("../../../docs/SPEC.md", import.meta.url);
export const appendixMarker =
  "## Appendix C. What the agent sees (regenerated by contract tests)";

/** Replace only nondeterministic identifiers, receipt times, and SQL timing. */
function normalizeMcpFixture(value: unknown): z.infer<typeof mcpFixtureSchema> {
  const identifiers = new Map<string, string>();
  const normalize = (value: JsonValue, field = ""): JsonValue => {
    if (Array.isArray(value)) return value.map((item) => normalize(item));
    if (value !== null && typeof value === "object")
      return Object.fromEntries(
        Object.entries(value).map(([key, item]) => [key, normalize(item, key)]),
      );
    if (field === "duration_ms") return 0;
    if (typeof value !== "string") return value;
    if (/^\d{4}-\d\d-\d\dT/.test(value)) return "2026-09-07T01:00:00.000Z";
    if (
      /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(
        value,
      )
    ) {
      if (!identifiers.has(value))
        identifiers.set(
          value,
          `00000000-0000-4000-8000-${String(identifiers.size + 1).padStart(12, "0")}`,
        );
      return identifiers.get(value) ?? value;
    }
    if (field === "organization_id") return "fixture-organization";
    return value;
  };
  return mcpFixtureSchema.parse(normalize(jsonValueSchema.parse(value)));
}
export async function renderAppendix(
  fixture: z.infer<typeof mcpFixtureSchema>,
): Promise<string> {
  const markdown = `${appendixMarker}\n\nGenerated from the real PostgreSQL and ClickHouse and official MCP SDK contract fixture at\n\`fixtures/contracts/mcp.json\`. Regenerate with\n\`UPDATE_MCP_FIXTURES=1 pnpm exec vitest run apps/api/test/transport.integration.test.ts\`.\nIdentifiers, receipt timestamps, and SQL timings are normalized for reproducibility.\n\nRead keys list \`search\`, \`get\`, \`sql\`, \`dashboard_list\`, \`dashboard_save\`, and\n\`dashboard_delete\`; effective admin keys also list\n\`set_visibility\`, \`purge\`, \`audit\`, and \`status\`.\n\n\`tools/list\` input contracts (output schemas are present in the fixture):\n\n\`\`\`json\n${JSON.stringify(
    fixture.tools.map(({ name, description, inputSchema, annotations }) => ({
      name,
      description,
      inputSchema,
      annotations,
    })),
    null,
    2,
  )}\n\`\`\`\n\n${(
    [
      ["search", formatSearch(fixture.search)],
      ["get", formatGet(fixture.get)],
      ["sql", formatSql(fixture.sql)],
    ] as const
  )
    .map(
      ([name, formatted]) =>
        `\`${name}\` text rendering; structuredContent contains the corresponding schema-validated fixture value.\n\n\`\`\`text\n${formatted.text}\n\`\`\``,
    )
    .join(
      "\n\n",
    )}\n\nTool failures return \`isError: true\` and a text JSON error. They omit structuredContent\nbecause it would otherwise be validated against the tool's success output schema.\n`;
  return format(markdown, {
    ...(await resolveConfig(specUrl)),
    parser: "markdown",
  });
}
export async function checkMcpFixture(value: unknown): Promise<void> {
  const fixture = normalizeMcpFixture(value);
  if (process.env.UPDATE_MCP_FIXTURES === "1") {
    await mkdir(new URL(".", fixtureUrl), { recursive: true });
    await writeFile(fixtureUrl, `${JSON.stringify(fixture, null, 2)}\n`);
    const spec = await readFile(specUrl, "utf8");
    await writeFile(
      specUrl,
      `${spec.slice(0, spec.indexOf(appendixMarker))}${await renderAppendix(fixture)}`,
    );
  } else {
    const expected = mcpFixtureSchema.parse(
      JSON.parse(await readFile(fixtureUrl, "utf8")),
    );
    if (JSON.stringify(fixture) !== JSON.stringify(expected))
      throw new Error(
        "The MCP contract fixture changed. Review and regenerate Appendix C.",
      );
  }
}
export async function readMcpFixture() {
  return mcpFixtureSchema.parse(JSON.parse(await readFile(fixtureUrl, "utf8")));
}
